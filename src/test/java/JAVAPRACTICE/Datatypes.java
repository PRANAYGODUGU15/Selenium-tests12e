package JAVAPRACTICE;


public class Datatypes {

	public static void main(String[] args) {
		
		//Numeric data types
		
		int a = 100, b=200;
		
		System.out.println("the sum is:"+(a+b));
		System.out.println(a+" ,"+b);
		
		byte c = 125;
		System.out.println("the value of c is:" +c);
		
		short sh = 3535;
		System.out.println(sh);
		
		long l = 6146328622652L; // At the end of the value need to specify Literal which represent with l upper or lower case
		System.out.println(l);
		
		//Decimal Numbers
		
		float itemprice = 15.5015f;//need to specify the literal like f/F
		System.out.println(itemprice);
		
		double d =  15.25;
		
		System.out.println(d);
		
		char grad = 'A';
		System.out.println(grad);
		
		
		String name = "john"; // string is a non primitive type
		System.out.println(name);
		
		
		boolean bl = true;                //Allows only true or false.c
		System.out.println(bl);
		
		boolean bl1 = false;
		System.out.println(bl1);
	
	} 

}
